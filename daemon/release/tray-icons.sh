#!/usr/bin/env bash
# The tray's icons: the Copland mark (public/favicon.svg) in four states, as
# SVG sources and the PNGs the tray embeds (include_bytes!, see
# daemon/README.md). Run from anywhere; rerun after a change to the mark, to
# nord's roles in src/styles/themes.css, or to this script, and commit what it
# writes:
#   daemon/release/tray-icons.sh
# writes daemon/release/tray/<state>.svg and daemon/release/tray/<state>/<size>.png,
# rendering with icons.sh (rsvg-convert or resvg on PATH).
#
# Every colour is a role of the default theme (nord), read from themes.css:
#   idle     the plain mark: bar behind, accent for the mark (as the favicon)
#   working  the mark with a green badge (a run is going)
#   needs    the mark with an orange badge (an agent needs you, or a last run failed)
#   stopped  no daemon answers the socket: the mark in muted on bar, no badge,
#            the whole icon at reduced opacity so it reads as greyed out on a
#            light panel and a dark one
# The badge has a ring of bar round it, so it stands apart from the mark.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
out=$here/tray
sizes=(16 22 24 32 48 64)

# A role of the nord block (the first one in themes.css) as #rrggbb.
role() {
  local rgb
  rgb=$(awk -v name="--$1:" '$1 == name { print $2, $3, $4; exit }' "$repo/src/styles/themes.css" | tr -d ';')
  [ -n "$rgb" ] || { echo "tray-icons.sh: no --$1 in themes.css" >&2; exit 1; }
  # shellcheck disable=SC2086
  printf '#%02x%02x%02x' $rgb
}
bar=$(role bar) accent=$(role accent) green=$(role green) orange=$(role orange) muted=$(role muted)

# The mark's paths from the favicon, recoloured to the given role.
mark() {
  grep '<path' "$repo/public/favicon.svg" | sed -E "s/(fill|stroke)=\"#[0-9a-fA-F]{6}\"/\1=\"$1\"/"
}

badge() {
  echo "  <circle cx=\"12.5\" cy=\"12.5\" r=\"3.25\" fill=\"$1\" stroke=\"$bar\" stroke-width=\"1.5\"/>"
}

# icon NAME MARK_COLOUR OPACITY [BADGE_COLOUR]
icon() {
  {
    echo '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">'
    echo "<!-- Generated by daemon/release/tray-icons.sh from public/favicon.svg; edit the script, not this file. -->"
    echo "<g opacity=\"$3\">"
    echo "  <rect width=\"16\" height=\"16\" fill=\"$bar\"/>"
    mark "$2"
    if [ -n "${4:-}" ]; then badge "$4"; fi
    echo '</g>'
    echo '</svg>'
  } >"$out/$1.svg"
  "$here/icons.sh" "$out/$1.svg" "$out/$1" "${sizes[@]}"
}

mkdir -p "$out"
icon idle "$accent" 1
icon working "$accent" 1 "$green"
icon needs "$accent" 1 "$orange"
icon stopped "$muted" 0.7
